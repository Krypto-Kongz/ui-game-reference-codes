#!/usr/bin/env node
// Regenerates examples/build-sample/, the checked-in example of what `hag build` hands a
// buyer: the per-buyer GuardData_* modules, the runtime copy with GuardKey.ts for SKU
// "demo", BUYER-README.md and LICENSE-BUYER.md, plus ACTIVATION-EXAMPLE.md with the
// activation message `hag issue` prints for a license bound to world 123.
//
// It uses the public demo key (examples/demo-keys/demo-private.json, the private half of
// runtime/GuardKey.ts) in a throwaway HAG_HOME, so nothing here is a secret and the sample
// license proves nothing. Run it again whenever runtime/GuardCore.ts, the example data or
// the templates change, so the sample stays what the current tool produces:
//   node examples/make-build-sample.mjs      (or: npm run build:sample)
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requestCode } from '../cli/lib/formats.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const PKG = join(here, '..');
const HAG = join(PKG, 'cli', 'hag.mjs');
const SAMPLE = join(here, 'build-sample');
const CONFIG = join(here, 'hag.config.json');
const DEMO_KEY = join(here, 'demo-keys', 'demo-private.json');
const BUYER = 'b001';
const WORLD = '123';

const home = mkdtempSync(join(tmpdir(), 'hag-sample-'));
mkdirSync(join(home, 'keys'), { recursive: true });
copyFileSync(DEMO_KEY, join(home, 'keys', 'demo.json'));

function hag(args) {
  const env = { ...process.env, HAG_HOME: home };
  delete env.HAG_KEY_PASSPHRASE;
  const r = spawnSync(process.execPath, [HAG, ...args], { encoding: 'utf8', cwd: PKG, env });
  if (r.status !== 0) {
    console.error('hag ' + args.join(' ') + ' failed:\n' + (r.stdout || '') + (r.stderr || ''));
    process.exit(1);
  }
  return r.stdout || '';
}

rmSync(SAMPLE, { recursive: true, force: true });
hag(['buyer', 'add', '--sku', 'demo', '--id', BUYER, '--name', 'Ana']);
const built = hag(['build', '--sku', 'demo', '--buyer', BUYER, '--config', CONFIG, '--out', SAMPLE]);
const req = requestCode('demo', WORLD);
const issued = hag(['issue', '--sku', 'demo', '--buyer', BUYER, '--req', req]);
const begin = issued.indexOf('---- activation message (copy from here) ----');
const end = issued.indexOf('---- end ----');
if (begin < 0 || end < 0) {
  console.error('could not find the activation message in the hag issue output:\n' + issued);
  process.exit(1);
}
const message = issued.slice(begin + '---- activation message (copy from here) ----'.length, end).trim();
const licenseLine = issued.split('\n').find((l) => l.startsWith('LICENSE: ')) || '';
const license = licenseLine.slice('LICENSE: '.length).trim();

const doc =
  '# Activation example\n\n' +
  'What the seller sends the buyer after `hag issue`, for this sample package. The buyer of this\n' +
  'package pressed Play in world `' + WORLD + '` and sent the request code `' + req + '` (the\n' +
  'console line `[AssetGuard] I01 no license, trial mode. Activation request code: ' + req + '`);\n' +
  'the seller ran:\n\n' +
  '```\n' +
  'hag issue --sku demo --buyer ' + BUYER + ' --req ' + req + '\n' +
  '```\n\n' +
  'The license is signed with the public demo key (`examples/demo-keys/`), so it proves nothing\n' +
  'and works only with the `GuardData_*.ts` files in this folder (they were encrypted under the\n' +
  "same buyer key). It is bound to world " + WORLD + ": in any other world the console prints `E12` and a\n" +
  'fresh request code. The whole sample is regenerated by `node examples/make-build-sample.mjs`.\n\n' +
  '## The license, in one piece\n\n' +
  '```\n' + license + '\n```\n\n' +
  '## The activation message, as printed\n\n' +
  '---\n\n' +
  message + '\n';
writeFileSync(join(SAMPLE, 'ACTIVATION-EXAMPLE.md'), doc);
rmSync(home, { recursive: true, force: true });

function sizes(dir) {
  let total = 0;
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    total += statSync(p).isDirectory() ? sizes(p) : statSync(p).size;
  }
  return total;
}
console.log(built.trimEnd());
console.log('hag issue: license for world ' + WORLD + ' (' + license.length + ' chars) -> ' + relative(PKG, join(SAMPLE, 'ACTIVATION-EXAMPLE.md')));
console.log('examples/build-sample: ' + sizes(SAMPLE) + ' bytes in total');
