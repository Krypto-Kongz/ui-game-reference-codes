// guardkey.mjs
// Reads and writes GuardKey.ts, the per-SKU generated runtime file (contract section 1):
// the seller's PUBLIC key plus the build-time policy. `hag keygen` writes it (keeping the
// policy values of an existing file), `hag build` composes the buyer copy from the SKU key
// record and the seller's policy file, `hag doctor` reads KEYSTONE_MODE from it.
// The rendered file must pass test/lint-runtime.mjs and TypeScript 4.7.4 strict.
import { isoDay } from './common.mjs';

export const KEYSTONE_MODES = ['off', 'warn', 'degrade'];
export const POLICY_DEFAULTS = { graceMs: 0, keystoneId: '0', keystoneMode: 'off', bakedLicense: '' };

// Single-quoted TypeScript string literal (the values here are base64url, digits, a SKU or
// a license, but escaping is cheap insurance against a hand-edited policy file).
export function tsString(s) {
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '') + "'";
}

export function renderGuardKey({ sku, pubN, pubE, graceMs, keystoneId, keystoneMode, bakedLicense }, when = isoDay()) {
  const mode = KEYSTONE_MODES.includes(keystoneMode) ? keystoneMode : 'off';
  return (
    '// GuardKey.ts\n' +
    '// Generated by `hag keygen` for SKU "' + sku + '" (' + when + '). This file ships with the game and\n' +
    '// holds only the public key and the build-time policy; there is no secret in it.\n' +
    '//   PUB_N / PUB_E    RSA-2048 public key (base64url big-endian modulus, exponent) every\n' +
    '//                    GuardData_* module and AssetGuard verify licenses against.\n' +
    '//   GRACE_MS         with no license: how long tier stays 0 before tier 1 (0 = at once).\n' +
    '//                    Data is trial regardless until a license is pasted (there is no key).\n' +
    '//   KEYSTONE_ID      seller-owned asset id that GuardKeystone spawns; "0" = none.\n' +
    "//   KEYSTONE_MODE    'off' | 'warn' | 'degrade'. `hag doctor` refuses 'degrade' unless a\n" +
    '//                    keystone-test record for this SKU is newer than 90 days.\n' +
    "//   BAKED_LICENSE    optional pre-issued license (zero-step activation); '' = none.\n" +
    '// Policy lives in generated source, never in a prop a buyer can edit. Re-running keygen\n' +
    '// keeps these policy values and replaces only SKU / PUB_N / PUB_E.\n' +
    'export const SKU: string = ' + tsString(sku) + ';\n' +
    'export const PUB_N: string = ' + tsString(pubN) + ';\n' +
    'export const PUB_E: number = ' + String(pubE) + ';\n' +
    'export const GRACE_MS: number = ' + String(Math.max(0, Math.floor(Number(graceMs) || 0))) + ';\n' +
    'export const KEYSTONE_ID: string = ' + tsString(keystoneId || '0') + ';\n' +
    "export const KEYSTONE_MODE: 'off' | 'warn' | 'degrade' = " + tsString(mode) + ';\n' +
    'export const BAKED_LICENSE: string = ' + tsString(bakedLicense || '') + ';\n'
  );
}

function unquote(lit) {
  const q = lit[0];
  const body = lit.slice(1, -1);
  return q === '`' ? body : body.replace(/\\(['"\\])/g, '$1');
}

// Pulls the exported constants out of a GuardKey.ts text. Missing or unparsable fields are
// null so callers can fall back to POLICY_DEFAULTS and say so.
export function parseGuardKey(text) {
  const str = (name) => {
    const m = new RegExp('export\\s+const\\s+' + name + '\\b[^=]*=\\s*(\'(?:[^\'\\\\]|\\\\.)*\'|"(?:[^"\\\\]|\\\\.)*"|`[^`]*`)\\s*;', 'm').exec(text);
    return m ? unquote(m[1]) : null;
  };
  const num = (name) => {
    const m = new RegExp('export\\s+const\\s+' + name + '\\b[^=]*=\\s*(-?\\d+(?:\\.\\d+)?)\\s*;', 'm').exec(text);
    return m ? Number(m[1]) : null;
  };
  const mode = str('KEYSTONE_MODE');
  return {
    sku: str('SKU'),
    pubN: str('PUB_N'),
    pubE: num('PUB_E'),
    graceMs: num('GRACE_MS'),
    keystoneId: str('KEYSTONE_ID'),
    keystoneMode: mode !== null && KEYSTONE_MODES.includes(mode) ? mode : null,
    bakedLicense: str('BAKED_LICENSE'),
  };
}

// The policy half of a parsed file, with defaults where a field is missing.
export function policyOf(parsed) {
  return {
    graceMs: parsed && parsed.graceMs !== null ? parsed.graceMs : POLICY_DEFAULTS.graceMs,
    keystoneId: parsed && parsed.keystoneId !== null ? parsed.keystoneId : POLICY_DEFAULTS.keystoneId,
    keystoneMode: parsed && parsed.keystoneMode !== null ? parsed.keystoneMode : POLICY_DEFAULTS.keystoneMode,
    bakedLicense: parsed && parsed.bakedLicense !== null ? parsed.bakedLicense : POLICY_DEFAULTS.bakedLicense,
  };
}
